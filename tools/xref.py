FILES = sorted(glob.glob("docs/*.md")) + sorted(glob.glob("docs/deck/slides/*.html")) + ["sim/sim.py"]

def body(path):
    t = open(path, encoding="utf-8").read()
    if path.endswith(".html"):
        t = re.sub(r'<div class="notes">.*?</div>', " ", t, flags=re.S)   # 발표 노트는 제외
    return t

def main():
    print("=" * 92)
    print(" 전수 대조 — 문서 · 발표덱 · 계산 정본")
    print("=" * 92)
    issues = []
    for name, pat, canon, allow in TARGETS:
        rx = re.compile(pat)
        found = collections.defaultdict(set)
        for f in FILES:
            if not os.path.exists(f): continue
            for m in rx.finditer(body(f)):
                found[m.group("v")].add(os.path.basename(f))
        if not found: continue
        bad = [k for k in found if k != canon and k not in allow]
        print(f"\n{'!!' if bad else '  '} {name}   정본 {canon}")
        for k in sorted(found):
            tail = f"   ← 허용: {allow[k]}" if k in allow else ("   ← 확인 필요" if k in bad else "")
            print(f"     {k:>9}   {', '.join(sorted(found[k]))}{tail}")
        if bad: issues.append((name, bad))
    print("\n" + "=" * 92)
    if issues:
        print(f" 확인 필요 {len(issues)}건")
        for n, b in issues: print(f"   · {n} — {', '.join(b)}")
    else:
        print(" 전부 일치")
    print("=" * 92)
    return 1 if issues else 0

sys.exit(main())
